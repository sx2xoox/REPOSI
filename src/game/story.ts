export function storyObjective(c: { seen: string[]; cleared: number; pending: number }): StoryObjective {
  if (c.pending) return { title: '마을 · 돌아온 기록 전하기', detail: '주민들에게 이번 원정에서 발견한 사실을 전하고, 다음 조사 대상을 정하자.' };
  if (c.cleared >= 7) return { title: '남아 있는 귀환로 조사', detail: '1-1부터 7-3까지 다시 탐사하며 실종된 주민과 주인 없는 집의 흔적을 찾자.' };
  const floor = c.cleared >= 4 ? c.cleared + 1 : Math.min(4, [1,2,3,4].find(f => !c.seen.includes(`boss:${f}`)) ?? 4);
  return OBJECTIVES[floor];
}
