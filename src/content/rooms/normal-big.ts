// Normal templates for big rooms: 2x1 (34x9), 1x2 (17x18) and 2x2 (34x18).
// `M(half)` mirrors a left half into a symmetric row (34 wide rooms).
// Legend as in normal-1x1.ts.

import { defineRoom } from '../../game/defs';
import type { RoomShape } from '../../game/constants';

const M = (half: string) => half + [...half].reverse().join('');
/** 17-wide symmetric row from its left 9 chars (index 8 = centre column). */
const C = (left9: string) => left9 + [...left9.slice(0, 8)].reverse().join('');

function room(shape: RoomShape, id: string, difficulty: number, rows: string[], floors?: number[], weight = 1): void {
  defineRoom({ id: `n${shape}_${id}`, shape, kinds: ['normal'], difficulty, rows, floors, weight });
}

